/// <summary>
/// .NET 10 / WinForms projection of VB6 frmOrderEntry. Owns a single
/// scoped <see cref="OrderRepository"/> and an <see cref="InvoiceExporter"/>;
/// both are constructor-injected to support unit testing without spinning
/// up a real form.
/// </summary>
[SpecClaim("EH-1")]
public sealed class OrderEntryForm : Form
{
