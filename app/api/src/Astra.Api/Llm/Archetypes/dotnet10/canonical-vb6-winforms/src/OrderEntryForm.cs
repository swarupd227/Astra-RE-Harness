    /// <summary>
    /// EH-1 + INV-1: btnSubmit_Click handler. Validates customer field,
    /// inserts the Orders row via the repository, then writes the invoice
    /// via the exporter. OE-1 (On Error Goto DBErrHandler) lowers to a
    /// typed try/catch filtering on the DAO 3022 / 3134 codes the SME
    /// signed off on.
    /// </summary>
    [SpecClaim("EH-1")]
    [SpecClaim("INV-1")]
    [SpecClaim("INV-2")]
    [SpecClaim("OE-1")]
    [SpecClaim("DP-1")]
    [SpecClaim("SE-1")]
    [SpecClaim("EC-1")]
    [SpecClaim("EC-2")]
    private async void OnSubmitClick(object? sender, EventArgs e)
    {
        // DP-1: VB6 implicit txtCustomer (in String context) → explicit .Text.
        var customer = txtCustomer.Text?.Trim() ?? "";

        // INV-1 + EC-1: empty customer short-circuits with no external state touched.
        if (customer.Length == 0)
        {
            lblStatus.Text = "Customer required";
            return;
        }

        var orderId = long.TryParse(txtOrderId.Text, out var parsed) ? parsed : 0;

        try
        {
            // INV-2 + SE-1: exactly-once insert; RecordsAffected = 1 asserted
            // before any downstream side effect.
            await _orders.InsertAsync(new Order(orderId, customer));
        }
        catch (DbException ex) when (IsKnownDaoError(ex))
        {
            // OE-1: DBErrHandler equivalent. Show the message; do NOT
            // attempt the Excel export. Other DbException codes rethrow
            // and propagate as unhandled — matches VB6 default dialog.
            lblStatus.Text = ex.Message;
            return;
        }

        // The Excel write happens only on the success path — same as VB6.
        await _exporter.ExportInvoiceAsync(orderId, ResolveTargetPath(orderId));
        lblStatus.Text = "Submitted";
    }

    // OE-1: the VB6 handler branches on Err.Number 3022 (duplicate PK) and
    // 3134 (SQL syntax). Surface the same code filter explicitly. Other
    // codes are NOT swallowed — they bubble out of the catch.
    private static bool IsKnownDaoError(DbException ex) =>
        ex.ErrorCode == 3022 || ex.ErrorCode == 3134;

    // Hard-coded template path in the VB6 source becomes a per-order path
    // here. Q-1 (open question in the spec) asks whether to keep this
    // hard-coded or move to config; until the SME decides, the scaffold
    // surfaces it as a private method.
    private static string ResolveTargetPath(long orderId) =>
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments),
            "Orders", $"Invoice-{orderId}.xlsx");

