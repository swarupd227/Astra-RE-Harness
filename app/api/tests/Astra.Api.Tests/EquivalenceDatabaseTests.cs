using System.Text.Json.Nodes;
using Astra.Api.Validation.PhpEquivalence;
using Xunit;

namespace Astra.Api.Tests;

/// <summary>Seeded-database equivalence: the schema both sides get, the seeds, the table comparison, the locator.</summary>
public class EquivalenceDatabaseTests
{
    private static JsonObject O(string json) => (JsonObject)JsonNode.Parse(json)!;

    private const string HugeSchema = """
        -- users and notes (from a generated package)
        CREATE TABLE IF NOT EXISTS users (
            user_id INT AUTO_INCREMENT PRIMARY KEY,
            user_name VARCHAR(64) NOT NULL COMMENT 'login; may not contain ;',
            user_account_type TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
            user_state ENUM('active','suspended') DEFAULT 'active',
            user_last_login TIMESTAMP NULL ON UPDATE CURRENT_TIMESTAMP,
            UNIQUE KEY user_name_idx (user_name),
            KEY account_idx (user_account_type)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
        CREATE TABLE notes (
            note_id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
            note_text TEXT NOT NULL,
            user_id INT NOT NULL,
            "VALUE" VARCHAR(10),
            PRIMARY KEY (note_id),
            FOREIGN KEY (user_id) REFERENCES users(user_id)
        );
        INSERT INTO users (user_name) VALUES ('demo; user');
        """;

    [Fact]
    public void Statements_split_on_semicolons_outside_quotes_and_comments()
    {
        var s = EquivalenceDatabase.Statements(HugeSchema);
        Assert.Equal(3, s.Count);
        Assert.StartsWith("CREATE TABLE IF NOT EXISTS users", s[0]);
        Assert.Contains("'login; may not contain ;'", s[0]);
        Assert.Equal("INSERT INTO users (user_name) VALUES ('demo; user')", s[2]);
        Assert.Equal(new[] { "users", "notes" }, EquivalenceDatabase.Tables(s));
    }

    [Fact]
    public void The_schema_is_translated_for_sqlite()
    {
        var sqlite = EquivalenceDatabase.ToSqlite(EquivalenceDatabase.Statements(HugeSchema));
        var users = sqlite[0];
        Assert.Contains("\"user_id\" INTEGER PRIMARY KEY AUTOINCREMENT", users);
        Assert.DoesNotContain("AUTO_INCREMENT", users);
        Assert.DoesNotContain("UNSIGNED", users);
        Assert.DoesNotContain("COMMENT", users);
        Assert.DoesNotContain("ON UPDATE", users);
        Assert.DoesNotContain("ENGINE", users);
        Assert.Contains("user_state TEXT DEFAULT 'active'", users);
        Assert.Contains("UNIQUE (user_name)", users);
        Assert.DoesNotContain("account_idx", users);
        var notes = sqlite[1];
        Assert.Contains("\"note_id\" INTEGER PRIMARY KEY AUTOINCREMENT", notes);   // identity + PRIMARY KEY (note_id) clause
        Assert.DoesNotContain("PRIMARY KEY (note_id)", notes);
        Assert.Contains("FOREIGN KEY (user_id) REFERENCES users(user_id)", notes);
        Assert.Equal("INSERT INTO users (user_name) VALUES ('demo; user')", sqlite[2]);
    }

    [Fact]
    public void H2_is_told_which_keyword_column_names_to_accept()
    {
        Assert.Equal("", EquivalenceDatabase.H2NonKeywords("CREATE TABLE t (id INT, name TEXT)"));
        Assert.Equal("VALUE", EquivalenceDatabase.H2NonKeywords("CREATE TABLE t (id INT, value TEXT)"));
    }

    [Fact]
    public void Tables_compare_as_multisets_with_normalised_values()
    {
        var php = O("""{"notes":[{"note_id":2,"note_text":"b","user_id":"7","flag":true},{"note_id":1,"note_text":"a","user_id":7}]}""");
        var java = O("""{"notes":[{"note_id":1,"note_text":"a","user_id":7,"extra":null},{"note_id":2,"note_text":"b","user_id":7,"flag":1}]}""");
        Assert.Null(EquivalenceDatabase.CompareTables(php, java));

        var javaMissing = O("""{"notes":[{"note_id":1,"note_text":"a","user_id":7}]}""");
        var diff = EquivalenceDatabase.CompareTables(php, javaMissing);
        Assert.NotNull(diff);
        Assert.Contains("table notes: PHP has 2 row(s), Java 1", diff);
        Assert.Contains("only in PHP: {flag=1, note_id=2, note_text='b', user_id=7}", diff);
    }

    [Fact]
    public void Timestamps_both_sides_stamp_now_are_equal()
    {
        var now = new DateTimeOffset(2026, 11, 28, 12, 0, 0, TimeSpan.Zero);
        var php = O($$"""{"users":[{"user_id":1,"user_last_login":"2026-11-28 12:00:03","user_creation_timestamp":{{now.ToUnixTimeSeconds() + 2}}}]}""");
        var java = O($$"""{"users":[{"user_id":1,"user_last_login":"2026-11-28 12:00:09","user_creation_timestamp":{{now.ToUnixTimeSeconds() + 7}}}]}""");
        Assert.Null(EquivalenceDatabase.CompareTables(php, java, now));
        var old = O("""{"users":[{"user_id":1,"user_last_login":"2020-01-01 00:00:00"}]}""");
        Assert.NotNull(EquivalenceDatabase.CompareTables(old, java, now));
    }

    [Fact]
    public void Seeds_keep_only_known_vectors_tables_and_plain_values()
    {
        var input = """
            {"vectors":[
              {"id":"V1","tables":{"notes":[{"note_id":1,"note_text":"a","user_id":7,"meta":{"x":1}}],"ghosts":[{"id":1}]},"session":{"user_id":7}},
              {"id":"V9","tables":{"notes":[{"note_id":5}]}},
              {"id":"V2","tables":{}}
            ]}
            """;
        var plan = EquivalenceSeedWriter.Parse(input, new[] { "V1", "V2" }, new[] { "notes", "users" });
        Assert.Equal(new[] { "V1", "V2" }, plan.Tables.Keys.OrderBy(k => k));
        var row = (JsonObject)((JsonArray)plan.Tables["V1"]["notes"]!)[0]!;
        Assert.False(row.ContainsKey("meta"));
        Assert.Equal(7, row["user_id"]!.GetValue<int>());
        Assert.Equal(7, plan.Session["V1"]["user_id"]!.GetValue<int>());
        Assert.Contains("ghosts", plan.Note);

        var roundTrip = EquivalenceSeedWriter.FromJson(EquivalenceSeedWriter.ToJson(plan).ToJsonString())!;
        Assert.Equal("cache", roundTrip.Source);
        Assert.Equal(plan.Tables["V1"].ToJsonString(), roundTrip.Tables["V1"].ToJsonString());
    }

    [Fact]
    public void Engineer_seeds_win_and_ride_on_the_vector()
    {
        var spec = System.Text.Json.JsonDocument.Parse("{}").RootElement;
        var v = PhpEquivalenceVectors.Build(spec, new[] { O("""{"label":"mine","named":{"id":1},"db":{"notes":[{"note_id":1}]}}""") });
        Assert.Single(v);
        Assert.Equal("""{"notes":[{"note_id":1}]}""", v[0].Db!.ToJsonString());
        var plan = new SeedPlan(new Dictionary<string, JsonObject> { ["V1"] = O("""{"notes":[]}""") }, new Dictionary<string, JsonObject>(), "model", null, 0m, null);
        Assert.Equal("""{"notes":[{"note_id":1}]}""", PhpEquivalenceRunner.SeedFor(v[0], plan).ToJsonString());

        var bare = PhpEquivalenceVectors.Build(spec, new[] { O("""{"id":3,"label":"only inputs","db":{}}""") });
        Assert.Equal("""{"id":3}""", bare[0].Named.ToJsonString());   // db and label are not inputs
    }

    [Fact]
    public void A_seeded_run_adds_h2_to_the_pom_when_missing()
    {
        var pom = "<project><parent><artifactId>spring-boot-starter-parent</artifactId></parent><dependencies></dependencies></project>";
        var withH2 = PhpEquivalenceRunner.EnsureH2(pom);
        Assert.Contains("<artifactId>h2</artifactId><scope>test</scope>", withH2);   // the Boot parent manages the version
        Assert.Equal(withH2, PhpEquivalenceRunner.EnsureH2(withH2));
        Assert.Contains("<version>2.2.224</version>", PhpEquivalenceRunner.EnsureH2("<project><dependencies></dependencies></project>"));
    }

    // ── verdicts with tables and the session ────────────────────────────────

    [Fact]
    public void Same_return_but_different_tables_fails_and_same_tables_pass()
    {
        var php = O("""{"ok":true,"returnValue":true,"responseCode":200,"db":{"notes":[{"note_id":1,"note_text":"new","user_id":7}]}}""");
        var javaSame = O("""{"ok":true,"returnValue":true,"db":{"notes":[{"note_id":1,"note_text":"new","user_id":7}]}}""");
        var pass = EquivalenceComparer.Compare(php, javaSame);
        Assert.Equal("PASSED", pass.Status);
        Assert.EndsWith("and the tables match.", pass.Reason);

        var javaDiff = O("""{"ok":true,"returnValue":true,"db":{"notes":[]}}""");
        var fail = EquivalenceComparer.Compare(php, javaDiff);
        Assert.Equal("FAILED", fail.Status);
        Assert.Contains("tables differ", fail.Reason);
        Assert.Contains("table notes: PHP has 1 row(s), Java 0", fail.Diff);
    }

    [Fact]
    public void Session_writes_are_compared_when_the_java_method_takes_a_session()
    {
        var php = O("""{"ok":true,"returnValue":null,"session":{"user_id":7,"feedback_positive":["Saved"]},"sessionChanged":true}""");
        var same = EquivalenceComparer.Compare(php, O("""{"ok":true,"returnValue":null,"session":{"user_id":7,"feedback_positive":["Saved"]}}"""));
        Assert.Equal("PASSED", same.Status);
        var differs = EquivalenceComparer.Compare(php, O("""{"ok":true,"returnValue":null,"session":{"user_id":7}}"""));
        Assert.Equal("FAILED", differs.Status);
        Assert.Contains("session differs", differs.Reason);
        var noJavaSession = EquivalenceComparer.Compare(php, O("""{"ok":true,"returnValue":null}"""));
        Assert.Equal("PASSED", noJavaSession.Status);
        Assert.Contains(noJavaSession.Notes, n => n.Contains("session writes are not compared"));
    }

    [Fact]
    public void A_schema_gap_is_skipped_not_failed()
    {
        var phpGap = O("""{"ok":true,"exception":{"class":"PDOException","message":"SQLSTATE[HY000]: General error: 1 no such column: user_deleted"}}""");
        Assert.Equal("SKIPPED", EquivalenceComparer.Compare(phpGap, O("""{"ok":true,"returnValue":1}""")).Status);
        var javaGap = O("""{"ok":true,"exception":{"class":"BadSqlGrammarException","message":"PreparedStatementCallback; bad SQL grammar [SELECT x FROM y]"}}""");
        Assert.Equal("SKIPPED", EquivalenceComparer.Compare(O("""{"ok":true,"returnValue":1}"""), javaGap).Status);
        var noDb = O("""{"ok":true,"exception":{"class":"PDOException","message":"astra-equivalence: this run has no database (no seed for this vector)"}}""");
        Assert.Equal("SKIPPED", EquivalenceComparer.Compare(noDb, O("""{"ok":true,"returnValue":1}""")).Status);
    }

    // ── the Java method ─────────────────────────────────────────────────────

    [Fact]
    public void A_record_named_like_the_routine_is_not_the_target_and_services_rank_first()
    {
        var files = new[]
        {
            ("src/main/java/com/example/session/LoginStatus.java", """
                package com.example.session;
                /** Result of userIsLoggedIn: whether the session holds a logged-in user. */
                public record LoginStatus(boolean loggedIn) {
                    public static LoginStatus of(boolean b) { return new LoginStatus(b); }
                }
                """),
            ("src/main/java/com/example/session/SessionService.java", """
                package com.example.session;
                public class SessionService {
                    /** PHP Session::userIsLoggedIn */
                    public boolean userIsLoggedIn(java.util.Map<String, Object> session) { return session.get("user_logged_in") != null; }
                }
                """),
        };
        var ranked = JavaTargetLocator.Rank(files, "userIsLoggedIn", "Session");
        Assert.DoesNotContain(ranked, r => r.MethodName == "LoginStatus");
        Assert.Equal("com.example.session.SessionService", ranked[0].ClassName);
        Assert.Equal("userIsLoggedIn", ranked[0].MethodName);
    }
    [Fact]
    public void The_routines_verb_on_a_class_named_for_its_noun_is_the_target()
    {
        Assert.True(JavaTargetLocator.VerbOnNoun("createnote", "create", "noteservice"));
        Assert.False(JavaTargetLocator.VerbOnNoun("createnote", "create", "userservice"));
        Assert.False(JavaTargetLocator.VerbOnNoun("getnote", "ge", "noteservice"));
        var files = new[]
        {
            ("src/main/java/com/example/notes/NoteService.java", "package com.example.notes;\npublic class NoteService {\n  public boolean create(String noteText, long userId) { return true; }\n}\n"),
            ("src/main/java/com/example/notes/NoteController.java", "package com.example.notes;\npublic class NoteController {\n  public Object create(Object req) { return null; }\n}\n"),
        };
        var t = JavaTargetLocator.Find(files, "createNote", "NoteModel");
        Assert.NotNull(t);
        Assert.Equal("com.example.notes.NoteService", t!.ClassName);
    }

    [Fact]
    public void Pdo_false_for_no_row_equals_java_null_unless_the_method_returns_a_boolean()
    {
        var php = O("""{"ok":true,"returnValue":false,"responseCode":200}""");
        var pass = EquivalenceComparer.Compare(php, O("""{"ok":true,"returnValue":null,"declaredType":"UserRecord"}"""));
        Assert.Equal("PASSED", pass.Status);
        Assert.Contains(pass.Notes, n => n.Contains("PHP false (no row)"));
        Assert.Equal("FAILED", EquivalenceComparer.Compare(php, O("""{"ok":true,"returnValue":null,"declaredType":"Boolean"}""")).Status);
    }

    [Fact]
    public void A_runtime_file_the_run_cannot_open_is_skipped()
    {
        var php = O("""{"ok":true,"exception":{"class":"Error","message":"Failed opening required '../application/config/texts.php' (include_path='.:/usr/local/lib/php')"}}""");
        var v = EquivalenceComparer.Compare(php, O("""{"ok":true,"returnValue":1}"""));
        Assert.Equal("SKIPPED", v.Status);
        Assert.Contains("texts.php", v.Reason);
    }
    [Fact]
    public void A_tinyint_flag_equals_a_java_boolean_and_a_builtin_type_error_is_php_behaviour()
    {
        var flag = EquivalenceComparer.Compare(O("""{"ok":true,"returnValue":{"user_active":1,"user_deleted":0}}"""),
            O("""{"ok":true,"returnValue":{"__class":"UserProfile","userActive":true,"userDeleted":false}}"""));
        Assert.Equal("PASSED", flag.Status);
        Assert.Contains(flag.Notes, n => n.Contains("read as Java true"));
        Assert.Equal("FAILED", EquivalenceComparer.Compare(O("""{"ok":true,"returnValue":1}"""), O("""{"ok":true,"returnValue":false}""")).Status);

        var builtin = O("""{"ok":true,"exception":{"class":"TypeError","message":"array_walk_recursive(): Argument #1 ($array) must be of type array, false given"}}""");
        var v = EquivalenceComparer.Compare(builtin, O("""{"ok":true,"returnValue":null}"""));
        Assert.Equal("FAILED", v.Status);                       // PHP's own code throws where Java returns: a real difference
        var signature = O("""{"ok":true,"exception":{"class":"TypeError","message":"Foo::bar(): Argument #1 ($id) must be of type int, string given, called in x.php"}}""");
        Assert.Equal("SKIPPED", EquivalenceComparer.Compare(signature, O("""{"ok":true,"returnValue":1}""")).Status);
    }
